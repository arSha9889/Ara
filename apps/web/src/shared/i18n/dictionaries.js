function mergeDictionary(base, overrides) {
  const result = { ...base };

  Object.entries(overrides).forEach(([key, value]) => {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      result[key] = mergeDictionary(base[key] ?? {}, value);
      return;
    }
    result[key] = value;
  });

  return result;
}

