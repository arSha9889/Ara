export function localeFromSystem() {
  const language = navigator.language?.toLowerCase() ?? 'en';
  return language.startsWith('ru') ? 'ru' : 'en';
}

export function translate(language, path, variables = {}) {
  const value = path.split('.').reduce((current, segment) => current?.[segment], COPY[language] ?? COPY.en);
  if (typeof value !== 'string') return path;
  return value.replace(/\{(\w+)\}/g, (_, key) => String(variables[key] ?? `{${key}}`));
}
